// Release signing comes from keystore.properties (not committed) or environment variables.
val keystoreProps = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun signingValue(key: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv("PHONEHOP_" + key.uppercase())

val releaseStoreFile = signingValue("storeFile")?.let { rootProject.file(it) }?.takeIf { it.exists() }

